import { expect, story } from "../../stories/playwright/story"

story(
  "voice controls belong to the composer and its orb responds to microphone levels",
  async ({ mount, page }, testInfo) => {
    const root = await mount("opencode-composer-flow--integrated-voice")
    const actions = root.locator('[data-slot="composer-actions"]')
    await expect(actions.getByRole("button", { name: "Start voice", exact: true })).toBeVisible()
    await root.getByRole("textbox", { name: "Prompt", exact: true }).fill("Keep my draft")
    await actions.getByRole("button", { name: "Start voice", exact: true }).click()
    await expect(root.locator(".voice-integrated-status")).toHaveText("Connecting…")
    await expect(root.locator(".voice-integrated-status")).toHaveClass(/sr-only/)
    await expect(root.locator(".voice-orb")).toHaveAttribute("data-connecting", "true")
    await expect(root.locator(".voice-orb")).toHaveCSS("width", "48px")
    await root.getByRole("button", { name: "Connect fixture", exact: true }).click()
    await expect(root.locator(".voice-integrated-status")).toHaveText("Listening")
    await expect(root.locator(".voice-integrated-status")).toHaveClass(/sr-only/)
    const orb = root.locator(".voice-orb")
    await expect(orb).toHaveAttribute("data-connecting", "false")
    await expect(orb).toHaveCSS("width", "96px")
    await page.evaluate(() => document.fonts.ready.then(() => undefined))
    const centre = await root.locator(".voice-orb-space").boundingBox()
    const composer = await root.locator('[data-component="composer"]').boundingBox()
    expect(centre).not.toBeNull()
    expect(composer).not.toBeNull()
    expect(Math.abs(centre!.x + centre!.width / 2 - composer!.x - composer!.width / 2)).toBeLessThan(1)
    await expect(actions.getByRole("button", { name: "Mute", exact: true })).toHaveText("")
    const speaker = actions.getByRole("button", { name: "Silence audio", exact: true })
    await expect(speaker).toHaveText("")
    await speaker.click()
    await expect(actions.getByRole("button", { name: "Enable audio", exact: true })).toHaveAttribute(
      "aria-pressed",
      "true",
    )
    await expect(actions.getByRole("button", { name: "Mute", exact: true })).toHaveAttribute("aria-pressed", "false")
    await actions.getByRole("button", { name: "Enable audio", exact: true }).click()
    const speakerBox = await speaker.boundingBox()
    const microphoneBox = await actions.getByRole("button", { name: "Mute", exact: true }).boundingBox()
    const endBox = await actions.getByRole("button", { name: "End", exact: true }).boundingBox()
    expect(Math.round(microphoneBox!.x - speakerBox!.x - speakerBox!.width)).toBe(12)
    expect(Math.round(endBox!.x - microphoneBox!.x - microphoneBox!.width)).toBe(12)
    expect(Math.round(endBox!.width)).toBe(28)
    expect(endBox!.y + endBox!.height).toBeLessThanOrEqual(composer!.y + composer!.height - 7)
    await root.getByRole("button", { name: "User speaking", exact: true }).click()
    await expect.poll(() => orb.evaluate((element) => element.style.getPropertyValue("--voice-mic"))).toBe("0.75")
    await root.screenshot({ path: testInfo.outputPath("voice-active.png") })
    await actions.getByRole("button", { name: "Mute", exact: true }).click()
    await expect(root.locator(".voice-integrated-status")).toHaveText("Microphone muted")
    await expect(actions.getByRole("button", { name: "Unmute", exact: true })).toHaveAttribute("aria-pressed", "true")
    await expect(orb).toHaveAttribute("data-muted", "true")
    await expect.poll(() => orb.evaluate((element) => element.style.getPropertyValue("--voice-mic"))).toBe("0")
    await page.setViewportSize({ width: 440, height: 760 })
    await expect(actions.getByRole("button", { name: "End", exact: true })).toBeInViewport()
    await actions.getByRole("button", { name: "End", exact: true }).click()
    await expect(orb).toHaveCount(0)
    await expect(root.getByRole("textbox", { name: "Prompt", exact: true })).toHaveText("Keep my draft")
    await root.getByRole("textbox", { name: "Prompt", exact: true }).fill("")
    await actions.getByRole("button", { name: "Start voice", exact: true }).click()
    await root.getByRole("button", { name: "Connect fixture", exact: true }).click()
    await expect(actions.getByRole("button", { name: "Send", exact: true })).toHaveCount(0)
    await expect(actions.getByRole("button")).toHaveCount(3)
    await expect(actions.getByRole("button").nth(0)).toHaveAccessibleName("Silence audio")
    await expect(actions.getByRole("button").nth(1)).toHaveAccessibleName("Mute")
    await expect(actions.getByRole("button").nth(2)).toHaveAccessibleName("End")
  },
)
