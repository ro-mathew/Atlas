import { expect, story } from "../../stories/playwright/story"

story("Voice is a normal settings page and keeps local and hosted options accessible", async ({ mount, page }) => {
  const root = await mount("app-dialog-settings--voice")
  await expect(root.getByRole("heading", { name: "Voice", exact: true })).toBeVisible()
  await expect(root.getByRole("switch", { name: "Enable voice calls", exact: true })).toBeEnabled()
  await root.getByRole("switch", { name: "Enable voice calls", exact: true }).focus()
  await page.keyboard.press("Space")
  await expect(root.getByLabel("Local runtime", { exact: true })).toBeVisible()
  await root.getByLabel("Local runtime", { exact: true }).fill("/opt/voice/bin/python")
  await root.getByLabel("Local speech model", { exact: true }).fill("/opt/voice/model")
  await expect(root.getByLabel("Voice style", { exact: true })).toHaveValue(/warm, friendly, professional/)
  await expect(root.getByLabel("Voice delivery", { exact: true })).toHaveValue(/zero point zero five/)
  await root.getByLabel("Voice style", { exact: true }).fill("Use a calm, consistent speaker.")
  await root.getByLabel("Voice delivery", { exact: true }).fill("Read decimals digit by digit.")
  await expect(root.getByRole("button", { name: /^Voice Activity Delay / })).toContainText("1000 ms")
  await root.getByRole("button", { name: /^Voice Activity Delay / }).click()
  await page.getByRole("option", { name: "1500 ms", exact: true }).click()
  await root.getByRole("button", { name: /^Speech engine / }).click()
  await page.getByRole("option", { name: "Hosted", exact: true }).click()
  await expect(root.getByLabel("Input transcription model", { exact: true })).toBeVisible()
  await expect(root.getByRole("button", { name: /^Voice Activity Delay / })).toContainText("1500 ms")
  await expect(root.getByLabel("Voice style", { exact: true })).toHaveValue("Use a calm, consistent speaker.")
  await expect(root.getByLabel("Voice delivery", { exact: true })).toHaveValue("Read decimals digit by digit.")
  await expect(root.getByText("Ending a call stops audio.", { exact: false })).toBeVisible()
  await expect(root.getByRole("switch", { name: "Brief waiting audio", exact: true })).toBeChecked()
})
